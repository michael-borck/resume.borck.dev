#!/usr/bin/env python3
"""Generate a branching Ink story from cv-data.yml.

A hub-and-spoke interactive fiction: the valley crossroads (hub) leads to eight
places, each a CV section. Visiting all eight unlocks the ending. Each knot
carries a `# image:` tag the player uses for artwork.

  python3 scripts/generate_ink_story.py     # -> creative/ink/story.ink
  node scripts/compile_ink.mjs              # -> creative/ink/data/story.json
"""

from __future__ import annotations

import re
import yaml

IMG = "../world/assets/img/"

# (var, knot display, hub label, blurb, image, cv source)
PLACES = [
    ("keep",     "The Keep",            "The Keep — a career in roles",       "A fortress of long service where each banner is a post held.", IMG + "keep.png",   "experience"),
    ("tower",    "The Observatory",     "The Observatory — study & degrees",  "A tower of study under a sky of degrees and theses.",          IMG + "tower.png",  "education"),
    ("dojo",     "The Dojo",            "The Dojo — languages & tools",       "A training hall where languages and frameworks are weapons.", IMG + "dojo.png",   "skills"),
    ("chest",    "The Vault",           "The Vault — projects & creations",   "A treasure vault of built things and open-source relics.",      IMG + "chest.png",  "projects"),
    ("scroll",   "The Hall of Legends", "The Hall — honours & publications",  "A hall of trophies, awards and published tomes.",              IMG + "scroll.png", "achievements"),
    ("grounds",  "The Training Grounds","The Grounds — teaching & students",  "A field of chalk and candlelight where lessons never end.",     IMG + "dojo.png",   "teaching"),
    ("ruins",    "The Old Ruins",       "The Ruins — service & guilds",       "Broken pillars naming the guilds and rolls of honour.",        IMG + "ruins.png",  "service"),
    ("shore",    "The Far Shore",       "The Shore — life beyond work",       "Salt air, a telescope, and a kata at dawn.",                   IMG + "beach.png",  "interests"),
]


def load_cv() -> dict:
    with open("data/cv-data.yml") as f:
        return yaml.safe_load(f)


def clean(v) -> str:
    return re.sub(r"\s+", " ", str(v)).strip() if v is not None else ""


def ink_safe(s: str) -> str:
    # Ink treats [] and {} specially; strip brackets/braces from prose.
    return re.sub(r"[\[\]{}]", "", clean(s))


def facts(cv: dict, which: str, limit: int = 3) -> list[str]:
    lines: list[str] = []

    def push(s):
        s = ink_safe(s)
        if s and s not in lines:
            lines.append(s)

    if which == "experience":
        for j in cv.get("experience", []):
            push(f"{clean(j.get('title'))} at {clean(j.get('organization'))} ({clean(j.get('period'))}).")
    elif which == "education":
        for e in cv.get("education", []):
            push(f"{clean(e.get('degree'))}, {clean(e.get('institution'))} ({clean(e.get('year'))}).")
    elif which == "skills":
        for g, v in cv.get("skills", {}).items():
            vals = []
            if isinstance(v, dict):
                for sub, vv in v.items():
                    vals += vv if isinstance(vv, list) else [vv]
            else:
                vals = v if isinstance(v, list) else [v]
            push(f"{g.title()}: {', '.join(clean(x) for x in vals[:10])}.")
    elif which == "projects":
        for p in cv.get("projects", []):
            push(f"{clean(p.get('name'))}: {clean(p.get('description'))}")
    elif which == "achievements":
        for a in cv.get("achievements", []):
            push(a)
        for b in (cv.get("publications", {}) or {}).get("books", []) or []:
            push(f"Book: {clean(b.get('title'))}.")
    elif which == "teaching":
        t = cv.get("teaching", {})
        ph = t.get("philosophy", {})
        push(ph.get("core"))
        for m in t.get("satisfaction", []) or []:
            push(f"{clean(m.get('metric'))} — {clean(m.get('details'))}")
    elif which == "service":
        for group, lst in (cv.get("service", {}) or {}).items():
            for it in lst or []:
                push(f"{clean(it.get('role'))} — {clean(it.get('organization') or it.get('project'))}")
        for m in cv.get("memberships", []) or []:
            push(f"{clean(m.get('organization'))} ({clean(m.get('status'))})")
    elif which == "interests":
        ints = cv.get("interests", []) or []
        push("Away from work: " + ", ".join(clean(i) for i in ints) + ".")
    return lines[:limit]


def build(cv: dict) -> str:
    personal = cv.get("personal", {})
    name = clean(personal.get("name"))
    out: list[str] = []
    out.append("// Generated by scripts/generate_ink_story.py — do not edit by hand.")
    out.append("// A branching CV in Ink. Compile with: node scripts/compile_ink.mjs")
    out.append("")
    out.append("VAR visited_count = 0")
    for var, *_ in PLACES:
        out.append(f"VAR {var}_open = 1")
    out.append("")
    out.append(f"# image: {IMG}world-map.webp")
    out.append(f"You come to the crossroads of {name}'s working life — a small valley at dusk.")
    out.append("Eight places glow along the paths. Visit them all, and the valley will tell you the whole story.")
    out.append("")
    out.append("-> hub")
    out.append("")

    # Hub
    out.append("=== hub ===")
    out.append("# image: " + IMG + "world-map.webp")
    out.append("The crossroads. Wind moves the lanterns. {visited_count} of 8 places have been opened.")
    out.append("")
    for var, knot, label, *_ in PLACES:
        out.append(f"* {{{var}_open == 1}} [{label}] -> {var}")
    out.append("* [Ask about Michael] -> michael")
    out.append("* {visited_count >= 8} [Leave the valley, story complete] -> finale")
    out.append("")

    # Region knots
    for var, knot, label, blurb, image, source in PLACES:
        out.append(f"=== {var} ===")
        out.append(f"# image: {image}")
        out.append(f"You enter {knot}. {blurb}")
        out.append("")
        for f in facts(cv, source):
            out.append(ink_safe(f))
        out.append("")
        out.append(f"~ {var}_open = 0")
        out.append("~ visited_count = visited_count + 1")
        out.append("-> hub")
        out.append("")

    # Michael / contact
    out.append("=== michael ===")
    out.append("# image: " + IMG + "camp.png")
    summary = ink_safe(cv.get("summary", {}).get("main", ""))
    if summary:
        out.append(summary)
        out.append("")
    out.append(f"{name} — {clean(personal.get('location'))}.")
    out.append(f"Reach out: {clean(personal.get('email'))}.")
    out.append("-> hub")
    out.append("")

    # Finale
    out.append("=== finale ===")
    out.append("# image: " + IMG + "camp.png")
    out.append(f"You have walked every path of the valley. The lanterns dim, satisfied.")
    out.append(f"This is {name}: a life of teaching, building, and the occasional very fast parser.")
    out.append(f"Say hello — {clean(personal.get('email'))} — or find him at {clean(personal.get('portfolio'))}.")
    out.append("")
    out.append("-> END")
    out.append("")
    return "\n".join(out)


def main() -> None:
    cv = load_cv()
    story = build(cv)
    import os
    os.makedirs("creative/ink", exist_ok=True)
    with open("creative/ink/story.ink", "w") as f:
        f.write(story)
    print("✓ Ink story: creative/ink/story.ink")
    print("  next: node scripts/compile_ink.mjs")


if __name__ == "__main__":
    main()