/* Resume World — game logic.
   Canvas 2D top-down engine: player movement with collision, follow camera,
   region discovery, landmark interaction. Loads data/world-data.json. */

(() => {
  "use strict";

  // ---- Config ----
  const PLAYER_SPEED = 168;      // px/sec (world px)
  const INTERACT_DIST = 58;      // px radius to trigger interaction
  const REGION_DIST = 120;       // px radius that counts as "entering" a region
  const PLAYER_SIZE = 26;        // player sprite size (world px)
  const PLAYER_RADIUS = 5;       // feet collision radius (world px, smaller than sprite)
  const LANDMARK_SIZE = 60;      // region landmark size (world px)
  const MARKER_SIZE = 34;        // small point-of-interest marker (world px)
  const FOLLOW_RATE = 0.16;      // camera smoothing
  const MAP_URL = "assets/img/world-map.webp";
  const COLLISION_URL = "assets/img/collision.json";
  const DATA_URL = "data/world-data.json";

  // Icon sprite file names (generated by scripts/resume_world_art.py).
  const ICONS = [
    "camp", "keep", "tower", "dojo", "library", "chest",
    "bridge", "beach", "signpost", "scroll", "ruins", "hero",
  ];

  // ---- DOM ----
  const canvas = document.getElementById("game");
  const ctx = canvas.getContext("2d");
  ctx.imageSmoothingEnabled = false;

  const el = {
    brandTitle: document.getElementById("brandTitle"),
    brandSub: document.getElementById("brandSub"),
    trackerList: document.getElementById("trackerList"),
    trackerTitle: document.getElementById("trackerTitle"),
    prompt: document.getElementById("prompt"),
    promptText: document.getElementById("promptText"),
    titlecard: document.getElementById("titlecard"),
    tcRegion: document.getElementById("tcRegion"),
    tcSub: document.getElementById("tcSub"),
    panel: document.getElementById("panel"),
    panelIcon: document.getElementById("panelIcon"),
    panelEyebrow: document.getElementById("panelEyebrow"),
    panelTitle: document.getElementById("panelTitle"),
    panelSub: document.getElementById("panelSub"),
    panelBody: document.getElementById("panelBody"),
    panelClose: document.getElementById("panelClose"),
    overlay: document.getElementById("overlay"),
    startBtn: document.getElementById("startBtn"),
    helpBtn: document.getElementById("helpBtn"),
    helpOverlay: document.getElementById("helpOverlay"),
    helpClose: document.getElementById("helpClose"),
    helpStart: document.getElementById("helpStart"),
    muteBtn: document.getElementById("muteBtn"),
    loading: document.getElementById("loading"),
    loadingBar: document.getElementById("loadingBar"),
  };

  // ---- State ----
  let world = null;
  const view = { w: 0, h: 0, dpr: 1 };
  const cam = { x: 0, y: 0 };
  const player = {
    x: 0, y: 0, dir: "down", moving: false,
    animT: 0, frame: 0,
  };
  const keys = Object.create(null);
  const found = new Set();        // discovered region ids
  let currentRegion = null;
  let nearLandmark = null;        // {region, marker} within INTERACT_DIST
  let started = false;
  let lastT = 0;
  let titlecardTimer = 0;
  let muted = true;

  // ---- Assets ----
  const images = {};
  let mapImg = null;
  let collision = null;          // { cols, rows, cells: Uint8Array (1=walk) }
  let collisionReady = false;

  function loadImage(src) {
    return new Promise((resolve, reject) => {
      const img = new Image();
      img.onload = () => resolve(img);
      img.onerror = () => reject(new Error("failed to load " + src));
      img.src = src;
    });
  }

  // Decode an RLE 0/1 stream (alternating runs starting with a 0-run) into a
  // flat Uint8Array of the given length.
  function decodeRle(rle, length) {
    const out = new Uint8Array(length);
    let i = 0, val = 0;
    for (let k = 0; k < rle.length && i < length; k++) {
      const run = rle[k];
      if (val === 1) out.fill(1, i, i + run);
      i += run;
      val = val ? 0 : 1;
    }
    return out;
  }

  // Decode the RLE collision stream into walkable + reachable grids.
  function decodeCollision(data) {
    const cols = data.cols, rows = data.rows;
    const cells = decodeRle(data.rle, cols * rows);
    const reach = data.reach ? decodeRle(data.reach, cols * rows) : cells;
    return { cols, rows, cells, reach };
  }

  async function loadAssets() {
    let done = 0;
    const total = ICONS.length + 2; // + map + hero
    const tick = () => {
      done++;
      if (el.loadingBar) el.loadingBar.style.width = Math.round((done / total) * 100) + "%";
    };
    const jobs = [];
    jobs.push(loadImage(MAP_URL).then((i) => { mapImg = i; tick(); }).catch(() => tick()));
    for (const name of ICONS) {
      jobs.push(loadImage(`assets/img/${name}.png`)
        .then((i) => { images[name] = i; tick(); })
        .catch(() => tick()));
    }
    await Promise.all(jobs);
    // Collision grid (optional: game still runs without it, just no map collision).
    try {
      const res = await fetch(COLLISION_URL);
      if (res.ok) {
        const data = await res.json();
        collision = decodeCollision(data);
        collisionReady = true;
      }
    } catch (e) {
      console.warn("collision map unavailable; using edge-only bounds", e);
    }
    // World data.
    const res = await fetch(DATA_URL);
    if (!res.ok) throw new Error("failed to load world data");
    world = await res.json();
  }

  // ---- Sizing ----
  function resize() {
    view.dpr = Math.min(window.devicePixelRatio || 1, 2);
    view.w = window.innerWidth;
    view.h = window.innerHeight;
    canvas.width = Math.floor(view.w * view.dpr);
    canvas.height = Math.floor(view.h * view.dpr);
    canvas.style.width = view.w + "px";
    canvas.style.height = view.h + "px";
    ctx.setTransform(view.dpr, 0, 0, view.dpr, 0, 0);
    ctx.imageSmoothingEnabled = false;
    layout = null; // world scale changed; rebuild snapped positions lazily
  }

  // ---- World geometry ----
  // The pixel-art map is drawn to fill a virtual world rectangle. We keep the
  // image's aspect ratio so the art is never distorted. The world is sized so
  // the map is only modestly larger than the viewport: the whole overworld is
  // readable in a couple of screens, and landmarks/player read at a sensible
  // scale relative to the terrain (not specks on a giant texture).
  function worldSize() {
    if (!mapImg) return { w: view.w * 1.4, h: view.h * 1.4 };
    // Scale so the map is ~1.15x the viewport on its larger axis.
    const cover = Math.max(view.w / mapImg.width, view.h / mapImg.height);
    const scale = cover * 1.15;
    return { w: mapImg.width * scale, h: mapImg.height * scale };
  }

  // ---- Layout ----
  // Region and marker world positions, snapped once onto walkable ground so a
  // landmark never sits in water or a mountain. Rebuilt on resize (world scale
  // changes with the viewport). Cheap: ~8 regions x a handful of markers.
  let layout = null;

  function ensureLayout() {
    if (layout || !world) return;
    const size = worldSize();
    // Snap a desired world point onto the nearest cell in the main landmass so
    // every landmark is guaranteed reachable on foot. Fall back to nearest
    // walkable, then the original point, if no reachable cell is nearby.
    const snap = (x, y, maxCells) => {
      if (!collisionReady) return { x, y };
      return nearestWalkable(x, y, maxCells, true)
        || nearestWalkable(x, y, maxCells, false)
        || { x, y };
    };
    const buildRegion = (r) => {
      const cx = (r.x / 100) * size.w;
      const cy = (r.y / 100) * size.h;
      const c = snap(cx, cy, 30);
      const list = r.markers || [];
      const ring = Math.min(78 + list.length * 10, 168);
      const markers = list.map((m, i) => {
        const ang = (Math.PI * 2 * i) / Math.max(list.length, 1) - Math.PI / 2;
        const p = snap(c.x + Math.cos(ang) * ring, c.y + Math.sin(ang) * ring, 12);
        return { marker: m, x: p.x, y: p.y };
      });
      return { region: r, x: c.x, y: c.y, markers };
    };
    layout = {
      regions: (world.regions || []).map(buildRegion),
      contact: world.contact
        ? (() => {
            const p = snap((world.contact.x / 100) * size.w, (world.contact.y / 100) * size.h, 30);
            return { x: p.x, y: p.y };
          })()
        : null,
    };
  }

  function regionPos(r) {
    ensureLayout();
    const e = layout && layout.regions.find((x) => x.region === r);
    if (e) return { x: e.x, y: e.y };
    const size = worldSize();
    return { x: (r.x / 100) * size.w, y: (r.y / 100) * size.h };
  }

  function landmarkPos(region, index) {
    ensureLayout();
    const e = layout && layout.regions.find((x) => x.region === region);
    const m = e && e.markers[index];
    return m ? { x: m.x, y: m.y } : { x: 0, y: 0 };
  }

  function contactPos() {
    ensureLayout();
    if (layout && layout.contact) return layout.contact;
    const size = worldSize();
    const c = world.contact || { x: 50, y: 50 };
    return { x: (c.x / 100) * size.w, y: (c.y / 100) * size.h };
  }

  // Find the nearest walkable point to (x, y) within `maxCells` grid cells.
  // With `reachableOnly`, only cells in the main landmass (connected to spawn)
  // qualify, so landmarks always snap onto ground the player can actually walk.
  function nearestWalkable(x, y, maxCells, reachableOnly) {
    const size = worldSize();
    const gx = Math.floor((x / size.w) * collision.cols);
    const gy = Math.floor((y / size.h) * collision.rows);
    const cw = size.w / collision.cols;
    const ch = size.h / collision.rows;
    const ok = reachableOnly
      ? (idx) => collision.reach[idx] === 1
      : (idx) => collision.cells[idx] === 1;
    for (let r = 0; r <= maxCells; r++) {
      for (let dy = -r; dy <= r; dy++) {
        for (let dx = -r; dx <= r; dx++) {
          if (Math.max(Math.abs(dx), Math.abs(dy)) !== r) continue;
          const nx = gx + dx, ny = gy + dy;
          if (nx < 0 || ny < 0 || nx >= collision.cols || ny >= collision.rows) continue;
          if (ok(ny * collision.cols + nx)) {
            return { x: (nx + 0.5) * cw, y: (ny + 0.5) * ch };
          }
        }
      }
    }
    return null;
  }

  // ---- Collision ----
  // Primary: per-cell walkability from collision.json (derived from map colors:
  // water, mountains, deep forest block). Fallback: edge-only bounds.
  const EDGE = 20;
  function walkable(x, y) {
    const size = worldSize();
    if (x <= EDGE || y <= EDGE || x >= size.w - EDGE || y >= size.h - EDGE) return false;
    if (!collisionReady) return true;
    const gx = Math.floor((x / size.w) * collision.cols);
    const gy = Math.floor((y / size.h) * collision.rows);
    if (gx < 0 || gy < 0 || gx >= collision.cols || gy >= collision.rows) return false;
    return collision.cells[gy * collision.cols + gx] === 1;
  }

  // Circle-vs-grid test with a radius, so the player can't clip corners.
  function canStand(x, y, radius) {
    const r = radius || 0;
    if (!walkable(x, y)) return false;
    if (r <= 0) return true;
    return walkable(x - r, y) && walkable(x + r, y) && walkable(x, y - r) && walkable(x, y + r);
  }

  function tryMove(dx, dy) {
    const nx = player.x + dx;
    const ny = player.y + dy;
    // Feet-sized collision box (smaller than the sprite) so the player slips
    // through 1-cell-wide paths instead of snagging on every corner.
    const rad = PLAYER_RADIUS;
    if (canStand(nx, player.y, rad)) player.x = nx;
    if (canStand(player.x, ny, rad)) player.y = ny;
  }

  // ---- Camera ----
  function updateCamera() {
    const size = worldSize();
    let cx = player.x - view.w / 2;
    let cy = player.y - view.h / 2;
    cx = Math.max(0, Math.min(cx, Math.max(0, size.w - view.w)));
    cy = Math.max(0, Math.min(cy, Math.max(0, size.h - view.h)));
    // Smooth follow.
    cam.x += (cx - cam.x) * FOLLOW_RATE;
    cam.y += (cy - cam.y) * FOLLOW_RATE;
  }

  // ---- Drawing helpers ----
  function drawWorld() {
    const size = worldSize();
    ctx.save();
    ctx.translate(-cam.x, -cam.y);
    if (mapImg) {
      ctx.drawImage(mapImg, 0, 0, size.w, size.h);
    } else {
      // Fallback procedural map (used only if the art fails to load).
      ctx.fillStyle = "#1d3b2a";
      ctx.fillRect(0, 0, size.w, size.h);
      ctx.fillStyle = "#2c5a3c";
      for (let i = 0; i < 60; i++) {
        const gx = (i * 97) % size.w;
        const gy = (i * 53) % size.h;
        ctx.fillRect(gx, gy, 24, 18);
      }
      ctx.fillStyle = "#22405e";
      ctx.beginPath();
      ctx.ellipse(size.w * 0.72, size.h * 0.78, size.w * 0.1, size.h * 0.09, 0, 0, Math.PI * 2);
      ctx.fill();
    }

    drawContact();
    drawRegions();
    drawLandmarks();
    drawPlayer();
    ctx.restore();
  }

  function drawContact() {
    if (!world || !world.contact) return;
    const p = contactPos();
    const icon = images.camp;
    const sz = LANDMARK_SIZE;
    ctx.save();
    // gentle glow so the home camp stands out
    const pulse = 0.5 + 0.5 * Math.sin(player.animT * 2);
    ctx.globalAlpha = 0.25 + 0.2 * pulse;
    ctx.fillStyle = "#ffcf6b";
    ctx.beginPath();
    ctx.arc(p.x, p.y, sz * 0.55, 0, Math.PI * 2);
    ctx.fill();
    ctx.restore();
    ctx.save();
    if (icon) {
      ctx.drawImage(icon, p.x - sz / 2, p.y - sz / 2, sz, sz);
    } else {
      ctx.fillStyle = "#ffcf6b";
      ctx.fillRect(p.x - sz / 4, p.y - sz / 4, sz / 2, sz / 2);
    }
    // label
    ctx.font = "700 11px 'JetBrains Mono', monospace";
    ctx.textAlign = "center";
    const label = "Base Camp";
    const tw = ctx.measureText(label).width;
    ctx.fillStyle = "rgba(10,12,22,0.85)";
    ctx.fillRect(p.x - tw / 2 - 6, p.y + sz / 2 + 2, tw + 12, 18);
    ctx.fillStyle = "#ffe6a8";
    ctx.fillText(label, p.x, p.y + sz / 2 + 15);
    ctx.restore();
  }

  function drawRegions() {
    if (!world) return;
    for (const r of world.regions) {
      const p = regionPos(r);
      const isFound = found.has(r.id);
      const isCurrent = currentRegion && currentRegion.id === r.id;
      // Landmark icon — sized to read as a real structure on the terrain.
      const icon = images[r.icon];
      const sz = LANDMARK_SIZE;
      if (icon) {
        ctx.save();
        const bob = isCurrent ? Math.sin(player.animT * 3) * 3 : 0;
        ctx.globalAlpha = isFound ? 1 : 0.6;
        ctx.drawImage(icon, p.x - sz / 2, p.y - sz / 2 + bob, sz, sz);
        ctx.restore();
      } else {
        ctx.save();
        ctx.globalAlpha = isFound ? 1 : 0.6;
        ctx.fillStyle = isFound ? "#ffcf6b" : "#8a8aa0";
        ctx.fillRect(p.x - sz / 4, p.y - sz / 4, sz / 2, sz / 2);
        ctx.restore();
      }
      // Region label (pill under the landmark).
      ctx.save();
      ctx.font = "700 12px 'JetBrains Mono', monospace";
      ctx.textAlign = "center";
      const label = r.name;
      const tw = ctx.measureText(label).width;
      const lx = p.x;
      const ly = p.y + sz / 2 + 12;
      ctx.globalAlpha = isFound ? 0.95 : 0.75;
      ctx.fillStyle = "rgba(10,12,22,0.85)";
      ctx.fillRect(lx - tw / 2 - 7, ly - 13, tw + 14, 20);
      ctx.fillStyle = isCurrent ? "#6ee0d8" : (isFound ? "#ffe6a8" : "#b8b8c8");
      ctx.fillText(label, lx, ly + 1);
      ctx.restore();
    }
  }

  function drawLandmarks() {
    if (!world) return;
    for (const r of world.regions) {
      const list = r.markers || [];
      for (let i = 0; i < list.length; i++) {
        const m = list[i];
        const p = landmarkPos(r, i, list.length);
        const isNear = nearLandmark && nearLandmark.region.id === r.id && nearLandmark.marker === m;
        // Show all markers once their region is discovered (points of interest).
        if (!found.has(r.id) && !isNear) continue;
        ctx.save();
        const bob = Math.sin(player.animT * 2 + i) * 2;
        const s = isNear ? MARKER_SIZE + 8 : MARKER_SIZE;
        if (isNear) {
          ctx.strokeStyle = "#ffcf6b";
          ctx.lineWidth = 2;
          ctx.beginPath();
          ctx.arc(p.x, p.y + bob, s * 0.62 + Math.sin(player.animT * 6) * 2, 0, Math.PI * 2);
          ctx.stroke();
        }
        const icon = images[m.icon] || images.signpost;
        if (icon) {
          ctx.globalAlpha = found.has(r.id) ? 1 : 0.5;
          ctx.drawImage(icon, p.x - s / 2, p.y - s / 2 + bob, s, s);
        } else {
          ctx.fillStyle = isNear ? "#ffcf6b" : "#cfcfe0";
          ctx.fillRect(p.x - s / 2, p.y - s / 2 + bob, s, s);
        }
        ctx.restore();
      }
    }
  }

  function drawPlayer() {
    const bob = player.moving ? Math.sin(player.animT * 10) * 1.5 : 0;
    const hero = images.hero;
    const s = PLAYER_SIZE;
    ctx.save();
    // shadow
    ctx.fillStyle = "rgba(0,0,0,0.35)";
    ctx.beginPath();
    ctx.ellipse(player.x, player.y + s / 2 - 2, s * 0.36, s * 0.16, 0, 0, Math.PI * 2);
    ctx.fill();
    if (hero) {
      // flip horizontally when facing left
      ctx.translate(player.x, player.y + bob);
      if (player.dir === "left") ctx.scale(-1, 1);
      ctx.drawImage(hero, -s / 2, -s / 2, s, s);
    } else {
      ctx.fillStyle = "#7ddc7d";
      ctx.fillRect(player.x - 10, player.y - 14, 20, 28);
      ctx.fillStyle = "#ffe6a8";
      ctx.fillRect(player.x - 8, player.y - 20, 16, 8);
    }
    ctx.restore();
  }

  // ---- Interaction ----
  function findNearby() {
    if (!world) return null;
    let best = null;
    let bestD = INTERACT_DIST;
    for (const r of world.regions) {
      const list = r.markers || [];
      for (let i = 0; i < list.length; i++) {
        if (!found.has(r.id)) continue; // only discoverable in found regions
        const m = list[i];
        const p = landmarkPos(r, i, list.length);
        const d = Math.hypot(player.x - p.x, player.y - p.y);
        if (d < bestD) { bestD = d; best = { region: r, marker: m }; }
      }
      // Also allow interacting with the region landmark itself.
      const rp = regionPos(r);
      const d = Math.hypot(player.x - rp.x, player.y - rp.y);
      if (d < bestD) { bestD = d; best = { region: r, marker: null }; }
    }
    return best;
  }

  function checkRegionEntry() {
    if (!world) return;
    for (const r of world.regions) {
      const p = regionPos(r);
      const d = Math.hypot(player.x - p.x, player.y - p.y);
      if (d < REGION_DIST) {
        if (currentRegion && currentRegion.id === r.id) return;
        currentRegion = r;
        const first = !found.has(r.id);
        found.add(r.id);
        updateTracker();
        if (first) {
          showTitlecard(r.name, r.subtitle);
          sfx("discover");
        }
        return;
      }
    }
    // Not in any region.
    if (currentRegion) {
      currentRegion = null;
      updateTracker();
    }
  }

  // ---- UI updates ----
  function updateTracker() {
    if (!world || !el.trackerList) return;
    el.trackerList.innerHTML = "";
    if (el.trackerTitle) {
      el.trackerTitle.textContent = `Regions · ${found.size}/${world.regions.length}`;
    }
    for (const r of world.regions) {
      const chip = document.createElement("button");
      chip.className = "region-chip";
      if (found.has(r.id)) chip.classList.add("found");
      if (currentRegion && currentRegion.id === r.id) chip.classList.add("current");
      chip.textContent = r.name;
      chip.addEventListener("click", () => {
        openRegion(r);
      });
      el.trackerList.appendChild(chip);
    }
  }

  function showTitlecard(title, sub) {
    if (!el.titlecard) return;
    el.tcRegion.textContent = title;
    el.tcSub.textContent = sub || "";
    el.titlecard.classList.add("show");
    titlecardTimer = 2.6;
  }

  function setPrompt(show, text) {
    if (!el.prompt) return;
    if (show) {
      el.promptText.innerHTML = text;
      el.prompt.classList.add("show");
    } else {
      el.prompt.classList.remove("show");
    }
  }

  function openMarker(region, marker) {
    if (!el.panel) return;
    el.panelIcon.src = `assets/img/${marker.icon}.png`;
    el.panelIcon.style.display = "";
    el.panelEyebrow.textContent = region.name;
    el.panelTitle.textContent = marker.name;
    el.panelSub.textContent = marker.subtitle || "";
    let html = "";
    for (const line of marker.body || []) {
      if (line) html += `<p>${escapeHtml(line)}</p>`;
    }
    el.panelBody.innerHTML = html || '<p class="muted">No further details.</p>';
    el.panel.classList.add("open");
    sfx("open");
  }

  function openRegion(region) {
    if (!el.panel) return;
    el.panelIcon.style.display = "none";
    el.panelEyebrow.textContent = "Region";
    el.panelTitle.textContent = region.name;
    el.panelSub.textContent = region.subtitle || "";
    let html = `<div class="region-grid">`;
    for (const m of region.markers || []) {
      html += `<button class="region-item" data-name="${escapeAttr(m.name)}">
        <img src="assets/img/${m.icon}.png" alt="" />
        <span><span class="ri-name">${escapeHtml(m.name)}</span><br><span class="ri-sub">${escapeHtml(m.subtitle || "")}</span></span>
      </button>`;
    }
    html += `</div>`;
    el.panelBody.innerHTML = html;
    el.panelBody.querySelectorAll(".region-item").forEach((btn) => {
      btn.addEventListener("click", () => {
        const name = btn.dataset.name;
        const m = (region.markers || []).find((x) => x.name === name);
        if (m) openMarker(region, m);
      });
    });
    el.panel.classList.add("open");
    sfx("open");
  }

  function openContact() {
    const c = world.contact;
    if (!c) return;
    el.panelIcon.src = `assets/img/camp.png`;
    el.panelIcon.style.display = "";
    el.panelEyebrow.textContent = "Base camp";
    el.panelTitle.textContent = c.name;
    el.panelSub.textContent = "Start here · get in touch";
    let html = `<p class="muted">${escapeHtml(world.summary || "")}</p>`;
    const links = c.links || {};
    html += `<div class="panel-links">`;
    if (links.email) html += `<a href="mailto:${escapeAttr(links.email)}">Email</a>`;
    if (links.linkedin) html += `<a href="${escapeAttr(links.linkedin)}" target="_blank" rel="noopener">LinkedIn</a>`;
    if (links.github) html += `<a href="${escapeAttr(links.github)}" target="_blank" rel="noopener">GitHub</a>`;
    if (links.portfolio) html += `<a href="${escapeAttr(links.portfolio)}" target="_blank" rel="noopener">Portfolio</a>`;
    html += `</div>`;
    el.panelBody.innerHTML = html;
    el.panel.classList.add("open");
    sfx("open");
  }

  function closePanel() {
    if (el.panel) el.panel.classList.remove("open");
    sfx("close");
  }

  // ---- Audio (tiny WebAudio chiptune blips) ----
  let audio = null;
  function ensureAudio() {
    if (audio) return;
    try { audio = new (window.AudioContext || window.webkitAudioContext)(); } catch (e) { audio = null; }
  }
  function sfx(kind) {
    if (muted) return;
    ensureAudio();
    if (!audio) return;
    const t = audio.currentTime;
    const notes = {
      discover: [523, 659, 784],
      open: [440],
      close: [330],
      step: [180],
    }[kind] || [440];
    notes.forEach((freq, i) => {
      const o = audio.createOscillator();
      const g = audio.createGain();
      o.type = "square";
      o.frequency.value = freq;
      g.gain.setValueAtTime(0.0001, t + i * 0.08);
      g.gain.exponentialRampToValueAtTime(0.08, t + i * 0.08 + 0.01);
      g.gain.exponentialRampToValueAtTime(0.0001, t + i * 0.08 + 0.12);
      o.connect(g).connect(audio.destination);
      o.start(t + i * 0.08);
      o.stop(t + i * 0.08 + 0.14);
    });
  }

  // ---- Input ----
  function setupInput() {
    window.addEventListener("keydown", (e) => {
      const k = e.key;
      if (["ArrowUp", "ArrowDown", "ArrowLeft", "ArrowRight", " "].includes(k)) e.preventDefault();
      keys[k] = true;
      if (k === "Escape") { closePanel(); return; }
      if (k === "e" || k === "E" || k === "Enter" || k === " ") {
        if (nearLandmark) {
          if (nearLandmark.marker) openMarker(nearLandmark.region, nearLandmark.marker);
          else openRegion(nearLandmark.region);
        } else {
          // Check if standing on contact camp.
          const c = world && world.contact ? contactPos() : null;
          if (c && Math.hypot(player.x - c.x, player.y - c.y) < INTERACT_DIST) openContact();
        }
      }
    });
    window.addEventListener("keyup", (e) => { keys[e.key] = false; });

    // Touch D-pad
    if (window.matchMedia("(pointer: coarse)").matches) {
      document.body.classList.add("touch");
    }
    document.querySelectorAll(".dpad button").forEach((btn) => {
      const dir = btn.dataset.dir;
      const press = (e) => { e.preventDefault(); keys["dpad-" + dir] = true; };
      const release = (e) => { e.preventDefault(); keys["dpad-" + dir] = false; };
      btn.addEventListener("touchstart", press, { passive: false });
      btn.addEventListener("touchend", release, { passive: false });
      btn.addEventListener("touchcancel", release, { passive: false });
      btn.addEventListener("mousedown", press);
      btn.addEventListener("mouseup", release);
      btn.addEventListener("mouseleave", release);
      if (dir === "action") {
        btn.addEventListener("click", () => {
          if (nearLandmark) {
            if (nearLandmark.marker) openMarker(nearLandmark.region, nearLandmark.marker);
            else openRegion(nearLandmark.region);
          }
        });
      }
    });

    // Also allow clicking a region landmark to open it (mouse users).
    canvas.addEventListener("click", (e) => {
      if (!world) return;
      const wx = e.clientX + cam.x;
      const wy = e.clientY + cam.y;
      for (const r of world.regions) {
        const p = regionPos(r);
        if (Math.hypot(wx - p.x, wy - p.y) < 30) { openRegion(r); return; }
      }
      // click a landmark
      for (const r of world.regions) {
        if (!found.has(r.id)) continue;
        const list = r.markers || [];
        for (let i = 0; i < list.length; i++) {
          const p = landmarkPos(r, i, list.length);
          if (Math.hypot(wx - p.x, wy - p.y) < 18) { openMarker(r, list[i]); return; }
        }
      }
    });

    if (el.panelClose) el.panelClose.addEventListener("click", closePanel);
    if (el.helpBtn) el.helpBtn.addEventListener("click", () => el.helpOverlay.classList.remove("hidden"));
    if (el.helpClose) el.helpClose.addEventListener("click", () => el.helpOverlay.classList.add("hidden"));
    if (el.helpStart) el.helpStart.addEventListener("click", () => el.helpOverlay.classList.add("hidden"));
    if (el.muteBtn) el.muteBtn.addEventListener("click", () => {
      muted = !muted;
      el.muteBtn.textContent = muted ? "♪ off" : "♪ on";
      el.muteBtn.setAttribute("aria-pressed", String(!muted));
      if (!muted) sfx("open");
    });
  }

  // ---- Update loop ----
  function update(dt) {
    if (!started) return;
    player.animT += dt;

    // Input vector
    let dx = 0, dy = 0;
    if (keys["ArrowLeft"] || keys["a"] || keys["A"] || keys["dpad-left"]) { dx -= 1; player.dir = "left"; }
    if (keys["ArrowRight"] || keys["d"] || keys["D"] || keys["dpad-right"]) { dx += 1; player.dir = "right"; }
    if (keys["ArrowUp"] || keys["w"] || keys["W"] || keys["dpad-up"]) { dy -= 1; player.dir = "up"; }
    if (keys["ArrowDown"] || keys["s"] || keys["S"] || keys["dpad-down"]) { dy += 1; player.dir = "down"; }

    const panelOpen = el.panel && el.panel.classList.contains("open");
    if (dx !== 0 || dy !== 0) {
      if (!panelOpen) {
        const len = Math.hypot(dx, dy) || 1;
        tryMove((dx / len) * PLAYER_SPEED * dt, (dy / len) * PLAYER_SPEED * dt);
        player.moving = true;
      } else {
        player.moving = false;
      }
    } else {
      player.moving = false;
    }

    // Camera
    updateCamera();

    // Region entry
    checkRegionEntry();

    // Near landmark
    nearLandmark = findNearby();

    // Contact proximity prompt
    let contactNear = false;
    if (world && world.contact) {
      const c = contactPos();
      if (Math.hypot(player.x - c.x, player.y - c.y) < INTERACT_DIST) contactNear = true;
    }

    // Prompt
    if (panelOpen) {
      setPrompt(false);
    } else if (nearLandmark) {
      const label = nearLandmark.marker
        ? nearLandmark.marker.name
        : `Enter ${nearLandmark.region.name}`;
      setPrompt(true, `<span class="key">E</span> ${escapeHtml(label)}`);
    } else if (contactNear) {
      setPrompt(true, `<span class="key">E</span> ${escapeHtml(world.contact.name)}`);
    } else {
      setPrompt(false);
    }

    // Titlecard fade
    if (titlecardTimer > 0) {
      titlecardTimer -= dt;
      if (titlecardTimer <= 0) el.titlecard.classList.remove("show");
    }
  }

  function render() {
    const size = worldSize();
    ctx.clearRect(0, 0, view.w, view.h);
    // Dark letterbox fill beyond the map.
    ctx.fillStyle = "#0b0e1a";
    ctx.fillRect(0, 0, view.w, view.h);
    drawWorld();
  }

  function loop(t) {
    if (!lastT) lastT = t;
    let dt = (t - lastT) / 1000;
    lastT = t;
    if (dt > 0.1) dt = 0.1; // clamp after tab switch
    update(dt);
    render();
    requestAnimationFrame(loop);
  }

  // ---- Boot ----
  function start() {
    if (el.overlay) el.overlay.classList.add("hidden");
    started = true;
    ensureAudio();
    updateTracker();
  }

  async function boot() {
    resize();
    window.addEventListener("resize", resize);
    setupInput();

    try {
      await loadAssets();
    } catch (err) {
      console.error(err);
      if (el.loading) el.loading.querySelector(".loading-bar")?.remove();
      return;
    }

    // Hide loader, show welcome.
    if (el.loading) el.loading.style.display = "none";
    if (el.brandTitle) el.brandTitle.textContent = (world.title || "Resume World").toUpperCase();
    if (el.brandSub) el.brandSub.textContent = world.subtitle || "";

    // Place player at spawn (contact camp). Prefer the collision map's
    // guaranteed-walkable centre, falling back to the data spawn percentage.
    const s = worldSize();
    let spawnX = (world.spawn?.x ?? 50) / 100 * s.w;
    let spawnY = (world.spawn?.y ?? 50) / 100 * s.h;
    if (collisionReady) {
      const snapped = nearestWalkable(spawnX, spawnY, 30, true) || nearestWalkable(spawnX, spawnY, 12, false);
      if (snapped) { spawnX = snapped.x; spawnY = snapped.y; }
    }
    player.x = spawnX;
    player.y = spawnY;
    cam.x = player.x - view.w / 2;
    cam.y = player.y - view.h / 2;

    if (el.startBtn) el.startBtn.addEventListener("click", start);
    // Allow Enter/Space to start.
    window.addEventListener("keydown", (e) => {
      if (!started && (e.key === "Enter" || e.key === " ")) start();
    });

    requestAnimationFrame(loop);

    // Debug hook (harmless in production; used by automated tests).
    window.__WORLD_DEBUG__ = () => {
      ensureLayout();
      return {
        player: { x: Math.round(player.x), y: Math.round(player.y) },
        cam: { x: Math.round(cam.x), y: Math.round(cam.y) },
        world: worldSize(),
        collision: collisionReady ? { cols: collision.cols, rows: collision.rows } : null,
        hereWalkable: walkable(player.x, player.y),
        found: Array.from(found),
        currentRegion: currentRegion ? currentRegion.id : null,
        near: nearLandmark ? (nearLandmark.marker ? nearLandmark.marker.name : nearLandmark.region.name) : null,
        regions: layout ? layout.regions.map((e) => ({
          id: e.region.id, x: Math.round(e.x), y: Math.round(e.y),
          walkable: walkable(e.x, e.y),
          dist: Math.round(Math.hypot(player.x - e.x, player.y - e.y)),
        })) : [],
        contact: layout && layout.contact ? { x: Math.round(layout.contact.x), y: Math.round(layout.contact.y) } : null,
        started,
      };
    };
  }

  // ---- Utils ----
  function escapeHtml(s) {
    return String(s == null ? "" : s)
      .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
  }
  function escapeAttr(s) { return escapeHtml(s); }

  boot();
})();